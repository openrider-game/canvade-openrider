let directions: Float64Array | null = null;

/** The table, decoded on the first use. */
function table(): Float64Array {
    if (directions === null) {
        const binary = atob(TABLE);
        const view = new DataView(new ArrayBuffer(binary.length));
        for (let i = 0; i < binary.length; i++) {
            view.setUint8(i, binary.charCodeAt(i));
        }
        directions = new Float64Array(ROTATIONS * 2);
        for (let i = 0; i < directions.length; i++) {
            directions[i] = view.getFloat64(i * 8, true);
        }
    }
    return directions;
}

/**
 * Direction of a rotation in degrees, as `[-sin, cos]` of it in radians: from the table for a
 * whole degree it covers, else computed by the engine.
 */
export function direction(rotation: number): [number, number] {
    const index = rotation - FIRST_ROTATION;
    if (Number.isInteger(index) && index >= 0 && index < ROTATIONS) {
        const values = table();
        return [values[index * 2], values[index * 2 + 1]];
    }
    const rad = (rotation * Math.PI) / 180;
    return [-Math.sin(rad), Math.cos(rad)];
}
