import { Layer } from 'canvade';
import { GameConfig } from '../../openrider/config/game-config';
import { TRACKUPLOAD_PATH } from '../../openrider/constants/request.constants';
import { LiveEditSession } from '../../openrider/live/live-edit-session';
import type { TrackCode } from '../../openrider/parser/track-format';
import { Requests } from '../../openrider/request/requests';
import { UPLOAD_TOOLBAR } from '../../openrider/tool/toolbar.constants';
import { TrackRenderer } from '../../openrider/track/track-renderer';
import { TrackInterfaceLayer } from '../track/layers/track-interface.layer';
import { TrackMainLayer } from '../track/layers/track-main.layer';
import { ButtonDefinition, ToolbarDefinition } from '../track/track-view.definitions';
import { TrackViewState } from '../track/track-view.state';
import type { ExportFormat } from '../session';
import { THUMBNAIL_HEIGHT, THUMBNAIL_WIDTH, TrackUploadLayer } from './layers/track-upload.layer';

/**
 * Lets the player frame the thumbnail of the track before uploading it, pushed by the generator
 * state with the generated track code and editor file in the session.
 *
 * Only the camera and fullscreen tools are available. The track is uploaded either as a track
 * code, merging the layers of each type, or as an editor file keeping its layers. Uploading
 * redirects to the page of the published track, cancelling pops back to the editing state.
 */
export class TrackUploadState extends TrackViewState {
    protected initLayers(): Map<string, Layer> {
        return new Map<string, Layer>([
            ['main', new TrackMainLayer(this)],
            ['overlay', new TrackUploadLayer()],
            ['interface', new TrackInterfaceLayer(this)],
        ]);
    }

    public getToolbars(): ToolbarDefinition[] {
        return [{ side: 'left', tools: UPLOAD_TOOLBAR }];
    }

    public override getButtons(): ButtonDefinition[] {
        return [
            {
                label: 'Cancel',
                x: 10,
                y: 10,
                width: 100,
                height: 26,
                verticalAlign: 'bottom',
                action: () => this.manager.pop(),
            },
            {
                label: 'Upload track code',
                x: -85,
                y: 10,
                width: 160,
                height: 26,
                horizontalAlign: 'center',
                verticalAlign: 'bottom',
                action: () => void this.upload('code'),
            },
            {
                label: 'Upload editor file',
                x: 85,
                y: 10,
                width: 160,
                height: 26,
                horizontalAlign: 'center',
                verticalAlign: 'bottom',
                action: () => void this.upload('editor'),
            },
        ];
    }

    /**
     * Renders the framed part of the track as a PNG data URL.
     *
     * The frame is displayed at half the thumbnail size, so the view is rendered at twice the zoom
     * and the thumbnail is cropped from its center at full size.
     */
    private createThumbnail(): string {
        const track = this.track;
        const thumbnail = document.createElement('canvas');
        thumbnail.width = THUMBNAIL_WIDTH;
        thumbnail.height = THUMBNAIL_HEIGHT;

        // Rendered on a canvas of the size of the view, without the interface
        const view = document.createElement('canvas');
        view.width = track.viewWidth;
        view.height = track.viewHeight;
        const viewContext = view.getContext('2d');
        const thumbnailContext = thumbnail.getContext('2d');
        if (!viewContext || !thumbnailContext) {
            throw new Error('Cannot retrieve thumbnail context');
        }

        // Twice the view zoom, whatever the pixel ratio: the thumbnail has a fixed size in pixels
        const zoomFactor = track.zoomFactor;
        track.zoomFactor = track.viewZoom * 2;
        viewContext.lineCap = 'round';
        viewContext.lineJoin = 'round';
        // Rendered synchronously: the thumbnail cannot wait for the workers
        TrackRenderer.render(viewContext, track, { fastRender: false });
        track.zoomFactor = zoomFactor;

        thumbnailContext.drawImage(
            view,
            (view.width - THUMBNAIL_WIDTH) / 2,
            (view.height - THUMBNAIL_HEIGHT) / 2,
            THUMBNAIL_WIDTH,
            THUMBNAIL_HEIGHT,
            0,
            0,
            THUMBNAIL_WIDTH,
            THUMBNAIL_HEIGHT,
        );

        return thumbnail.toDataURL('image/png');
    }

    /**
     * Uploads the track code or the editor file generated by the generator state, the bytes of
     * its track file sent as a file.
     */
    private async upload(format: ExportFormat): Promise<void> {
        const image = this.createThumbnail();
        const code = format === 'editor' ? this.session.editorCode : this.session.trackCode;
        const credits = LiveEditSession.of(this.track)?.credits ?? null;

        try {
            const response = await Requests.postFormJson<{ ID: number }>(
                GameConfig.url(TRACKUPLOAD_PATH),
                {
                    trackCode: TrackUploadState.bytes(code ?? ''),
                    thumbnail: image.replace('data:image/png;base64,', ''),
                    // The editors of an editing session, signed by its server
                    ...(credits === null ? {} : { credits }),
                },
            );

            // Races the published track, on the track page of the hosting page when it gives one
            location.href = GameConfig.trackPage(response.ID);
        } catch (e) {
            alert(`Your track was refused: ${e}`);
        }
    }

    /** Bytes of a track to upload: of its track file, or of its text. */
    private static bytes(code: TrackCode): Uint8Array<ArrayBuffer> {
        return typeof code === 'string' ? new TextEncoder().encode(code) : code.slice();
    }
}
